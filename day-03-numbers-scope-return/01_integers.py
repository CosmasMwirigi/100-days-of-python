"""
Day 3 of #100DaysOfPython: Integers (int)

int stands for integer: whole numbers like -2, -1, 0, 1, 2,
all the way towards negative and positive infinity. No decimal points.

Symbols for working with int:
+   add
-   subtract
*   multiply
/   divide
%   modulus: the remainder after division
//  floor divide: drops the remainder after division
"""

x = 7
y = 2

print(x + y)    # 9
print(x - y)    # 5
print(x * y)    # 14
print(x / y)    # 3.5
print(x % y)    # 1
print(x // y)   # 3
